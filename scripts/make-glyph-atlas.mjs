// Renders the menu bar digits to template PNGs, plus their metrics as a module.
// Run with: <electron> scripts/make-glyph-atlas.mjs  (or `pnpm icon`)
//
// The tray readout is a drawn bitmap, so anything set in a real typeface has to
// be rasterized somewhere. Doing it here rather than at runtime keeps the main
// process free of an offscreen window: the app just blits cells out of a PNG,
// exactly as it already does with the `t` mark.
//
// One row of fixed-width cells, one glyph per cell, black on transparent - a
// macOS template PNG carries only alpha, and the readout repaints it anyway.
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { app, BrowserWindow } from "electron";

const OUT_DIR = join(import.meta.dirname, "..", "assets", "tray");
const METRICS = join(import.meta.dirname, "..", "src", "main", "glyph-metrics.js");
// Every glyph a wait can contain: digits, ARR / BRD, and the `--` placeholder.
const ORDER = "0123456789ABDR-";
const SCALES = [
  ["Template.png", 1],
  ["Template@1x.png", 1],
  ["Template@2x.png", 2],
  ["Template@3x.png", 3],
];
const HEIGHT = 22; // the menu bar
// Sat on the mark's own baseline (48/66 of the bar), so the digits and the `t`
// share one line rather than each being centered on its own ink.
const BASELINE = (HEIGHT * 48) / 66;
// Menu bar text is around 13-14pt; 14 puts the digits' cap height just under the
// mark's 12pt of ink.
const SIZE = 14;
const FONT = `500 ${SIZE}px -apple-system, "SF Pro Text", system-ui, sans-serif`;

const page = (scale, cell) => `<!doctype html><canvas id="c"></canvas><script>
  const order = ${JSON.stringify(ORDER)};
  const scale = ${scale};
  const cell = ${cell};
  const c = document.getElementById("c");
  c.width = order.length * cell * scale;
  c.height = ${HEIGHT} * scale;
  const ctx = c.getContext("2d");
  ctx.scale(scale, scale);
  ctx.font = ${JSON.stringify(FONT)};
  ctx.fillStyle = "#000";
  ctx.textBaseline = "alphabetic";
  ctx.textAlign = "left";
  // Left-aligned in its own cell: the app advances by each glyph's real width,
  // so the cell only has to be wide enough for the widest of them.
  for (let i = 0; i < order.length; i++) ctx.fillText(order[i], i * cell, ${BASELINE});
  window.result = c.toDataURL("image/png");
</script>`;

// Measured in the same font, so the app can advance by the real glyph widths
// instead of padding every digit out to the widest one.
const measure = `<!doctype html><canvas id="c"></canvas><script>
  const ctx = document.getElementById("c").getContext("2d");
  ctx.font = ${JSON.stringify(FONT)};
  const m = ctx.measureText("8");
  window.result = JSON.stringify({
    advance: Object.fromEntries([...${JSON.stringify(ORDER)}].map((ch) => [ch, ctx.measureText(ch).width])),
    inkHeight: m.actualBoundingBoxAscent + m.actualBoundingBoxDescent,
  });
</script>`;

app.whenReady().then(async () => {
  await mkdir(OUT_DIR, { recursive: true });
  const window = new BrowserWindow({ show: false, width: 200, height: 100 });

  await window.loadURL(`data:text/html,${encodeURIComponent(measure)}`);
  const { advance, inkHeight } = JSON.parse(await window.webContents.executeJavaScript("window.result"));
  const round = (n) => Math.round(n * 100) / 100;
  const cell = Math.ceil(Math.max(...Object.values(advance)));

  for (const [suffix, scale] of SCALES) {
    await window.loadURL(`data:text/html,${encodeURIComponent(page(scale, cell))}`);
    const dataUrl = await window.webContents.executeJavaScript("window.result");
    const file = join(OUT_DIR, `glyphs${suffix}`);
    await writeFile(file, Buffer.from(dataUrl.split(",")[1], "base64"));
    console.log(`${file} (${ORDER.length * cell * scale}x${HEIGHT * scale})`);
  }

  await writeFile(
    METRICS,
    `// Generated by scripts/make-glyph-atlas.mjs - do not edit. Regenerate with \`pnpm icon\`.
// Logical points at menu bar scale, matching assets/tray/glyphs*.png.
export const GLYPH_ORDER = ${JSON.stringify(ORDER)};
export const GLYPH_CELL = ${cell};
export const GLYPH_BASELINE = ${round(BASELINE)};
export const GLYPH_INK_HEIGHT = ${round(inkHeight)};
export const GLYPH_ADVANCE = ${JSON.stringify(
      Object.fromEntries(Object.entries(advance).map(([ch, w]) => [ch, round(w)])),
      null,
      2,
    )};
`,
  );
  console.log(`${METRICS} (cell ${cell}pt, ink ${round(inkHeight)}pt)`);
  app.quit();
});
